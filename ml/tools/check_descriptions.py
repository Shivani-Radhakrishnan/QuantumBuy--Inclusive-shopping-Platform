"""Quality gate for the generated photo descriptions (assets/ai_descriptions.json).

    python ml/tools/check_descriptions.py

A description is kept only if it says something about the product's look and invents
nothing countable. Rejected: digits that aren't in the product name ("zoom of 100"),
field lists ("Colour: black, material: ..."), and sentences with no descriptive word
left once the product's own name is removed ("The honey is honey."). Kept descriptions
go in "descriptions"; the rest are listed under "rejected" with the reason, and the app
uses the hand-written text for those products.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DART_OUT = ROOT / "lib" / "data" / "photo_descriptions.dart"
sys.path.insert(0, str(ROOT / "ml"))

from quantumbuy_ml.catalog import DART_CATALOG, DESCRIPTIONS, parse_dart  # noqa: E402

DESCRIPTIVE = set("""
black white grey gray silver gold golden brown beige cream red maroon burgundy pink orange yellow green teal mint
blue navy purple violet clear transparent pale light dark bright shiny glossy matte metallic stainless steel glass
plastic leather wool cotton wooden metal fabric soft smooth round rectangular square curved flat slim sleek compact
long short tall small large wide striped floral paisley patterned spiral khaki colourful colorful
""".split())


def verdict(text: str, name: str) -> str | None:
    """None if the description is usable, otherwise the reason it is not."""
    if not text:
        return "empty"
    digits = set(re.findall(r"\d+", text)) - set(re.findall(r"\d+", name))
    if digits:
        return f"invented number {sorted(digits)[0]}"
    if ":" in text:
        return "field list, not a sentence"
    name_words = set(re.findall(r"[a-z]+", name.lower()))
    rest = {w for w in re.findall(r"[a-z]+", text.lower())} - name_words
    if not rest & DESCRIPTIVE:
        return "says nothing about the look"
    return None


def write_dart(kept: dict[str, str]) -> None:
    """The kept descriptions as a const map, so the app reads them without loading assets."""
    lines = ["// GENERATED by ml/tools/check_descriptions.py from assets/ai_descriptions.json. Do not edit.",
             "//", "// What a vision-language model saw in each product photo, after a quality check.",
             "// Products missing here keep their hand-written description only.", "",
             "/// Photo descriptions keyed by image asset path.",
             "const Map<String, String> photoDescriptions = {"]
    for image in sorted(kept):
        text = kept[image].replace("\\", "\\\\").replace("'", "\\'")
        lines.append(f"  '{image}': '{text}',")
    lines.append("};")
    DART_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    data = json.loads(DESCRIPTIONS.read_text(encoding="utf-8"))
    names = {p.image: p.name for p in parse_dart(DART_CATALOG.read_text(encoding="utf-8"))}
    every = {**data.get("descriptions", {}), **{k: v["text"] for k, v in data.get("rejected", {}).items()}}
    kept, rejected = {}, {}
    for image, text in every.items():
        why = verdict(text, names[image])
        if why:
            rejected[image] = {"text": text, "reason": why}
        else:
            kept[image] = text
    data["descriptions"], data["rejected"] = kept, rejected
    DESCRIPTIONS.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    write_dart(kept)
    print(f"kept {len(kept)} of {len(every)}")
    for image, r in rejected.items():
        print(f"  rejected {names[image]:20s} ({r['reason']}): {r['text']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
